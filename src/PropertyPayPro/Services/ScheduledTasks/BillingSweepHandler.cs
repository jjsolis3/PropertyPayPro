using System.Text;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using PropertyPayPro.Data;
using PropertyPayPro.Models;

namespace PropertyPayPro.Services.ScheduledTasks;

/// <summary>
/// Daily billing automation, driven by the switches in Settings > Billing.
/// Creating bills and applying late fees are both idempotent (existing
/// bills and fees are skipped), so a re-run or a manual Generate on the
/// same day never double-bills.
/// </summary>
public class BillingSweepHandler : IScheduledTaskHandler
{
    private readonly ApplicationDbContext _db;
    private readonly BillingService _billing;
    private readonly MailService _mail;
    private readonly AppSettingsService _settings;
    private readonly UserManager<ApplicationUser> _users;
    private readonly IAuditLog _audit;
    private readonly ILogger<BillingSweepHandler> _logger;

    public BillingSweepHandler(
        ApplicationDbContext db,
        BillingService billing,
        MailService mail,
        AppSettingsService settings,
        UserManager<ApplicationUser> users,
        IAuditLog audit,
        ILogger<BillingSweepHandler> logger)
    {
        _db = db;
        _billing = billing;
        _mail = mail;
        _settings = settings;
        _users = users;
        _audit = audit;
        _logger = logger;
    }

    public ScheduledTaskKind Kind => ScheduledTaskKind.BillingSweep;

    public async Task HandleAsync(ScheduledTask task, CancellationToken ct)
    {
        try
        {
            var s = await _settings.GetAsync(ct);
            if (!s.AutoGenerateCharges && !s.AutoApplyLateFees)
            {
                task.Description = "Billing automation is off (Settings > Billing).";
                return;
            }

            var today = DateOnly.FromDateTime(DateTime.UtcNow);
            var parts = new List<string>();

            var newBills = new List<RentalCharge>();
            if (s.AutoGenerateCharges)
            {
                if (today.Day >= s.AutoBillingDayOfMonth)
                {
                    newBills = await _billing.GenerateChargesForPeriodAsync(today.Year, today.Month);
                    parts.Add($"{newBills.Count} bill(s) created for {today:MMMM yyyy}");
                    if (newBills.Count > 0)
                    {
                        await _audit.WriteAsync("ChargesAutoGenerated", nameof(RentalCharge), null,
                            $"{newBills.Count} bill(s) for {today:MMMM yyyy}, total {newBills.Sum(c => c.AmountDue):C}",
                            overrideActor: "scheduler", ct: ct);
                    }
                }
                else
                {
                    parts.Add($"bills for {today:MMMM} start on day {s.AutoBillingDayOfMonth}");
                }
            }

            var fees = new List<RentalCharge>();
            if (s.AutoApplyLateFees)
            {
                fees = await _billing.ApplyAllLateFeesAsync();
                parts.Add($"{fees.Count} late fee(s) applied");
                if (fees.Count > 0)
                {
                    await _audit.WriteAsync("LateFeesAutoApplied", nameof(RentalCharge), null,
                        $"{fees.Count} late fee(s), total {fees.Sum(c => c.AmountDue):C}",
                        overrideActor: "scheduler", ct: ct);
                }
            }

            var baseUrl = await _settings.GetPublicBaseUrlAsync(ct);
            StatementResult? statements = null;
            if (s.AutoEmailStatements && newBills.Count > 0)
            {
                statements = await SendStatementsAsync(baseUrl, newBills.Select(c => c.LeaseId).Distinct(), ct);
                parts.Add(statements.Summary);
            }

            if (s.AutoEmailAdminSummary && newBills.Count + fees.Count > 0)
            {
                var sent = await SendAdminSummaryAsync(baseUrl, today, newBills, fees, statements, ct);
                parts.Add($"summary emailed to {sent} admin(s)");
            }

            task.Description = "Billing: " + string.Join("; ", parts) + ".";
            _logger.LogInformation("{Desc}", task.Description);
        }
        finally
        {
            RecurringTaskHelpers.EnqueueNextRun(_db, Kind, "Daily billing sweep");
        }
    }

    private record StatementResult(int Sent, int Skipped, int Failed)
    {
        public string Summary => $"statements: {Sent} sent, {Skipped} skipped, {Failed} failed";
    }

    private async Task<StatementResult> SendStatementsAsync(
        string baseUrl, IEnumerable<int> leaseIds, CancellationToken ct)
    {
        if (!_mail.IsConfigured) return new StatementResult(0, leaseIds.Count(), 0);

        int sent = 0, skipped = 0, failed = 0;
        foreach (var leaseId in leaseIds)
        {
            try
            {
                var log = await _mail.SendStatementAsync(baseUrl, leaseId, ct);
                if (log.Status == EmailStatus.Sent) sent++;
                else if (log.ToAddress.StartsWith('(')) skipped++; // no eligible tenant email
                else failed++;
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "Statement for lease {LeaseId} failed", leaseId);
                failed++;
            }
        }
        return new StatementResult(sent, skipped, failed);
    }

    private async Task<int> SendAdminSummaryAsync(
        string baseUrl, DateOnly today, List<RentalCharge> newBills, List<RentalCharge> fees,
        StatementResult? statements, CancellationToken ct)
    {
        if (!_mail.IsConfigured) return 0;

        var admins = (await _users.GetUsersInRoleAsync(IdentitySeed.AdminRole))
            .Where(u => !string.IsNullOrWhiteSpace(u.Email))
            .Select(u => u.Email!)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();
        if (admins.Count == 0) return 0;

        var ids = newBills.Concat(fees).Select(c => c.Id).ToList();
        var charges = await _db.RentalCharges
            .Where(c => ids.Contains(c.Id))
            .Include(c => c.Lease).ThenInclude(l => l!.Property)
            .Include(c => c.Lease).ThenInclude(l => l!.Tenants)
            .AsNoTracking()
            .ToDictionaryAsync(c => c.Id, ct);

        string Line(RentalCharge c) =>
            $"- {charges[c.Id].Lease?.Property?.Name} — {charges[c.Id].Lease?.TenantNames} — {c.AmountDue:C}";

        var sb = new StringBuilder();
        sb.AppendLine($"Automatic billing ran on {today:MMMM d, yyyy}.");
        sb.AppendLine();
        if (newBills.Count > 0)
        {
            sb.AppendLine($"New rent bills ({newBills.Count}, total {newBills.Sum(c => c.AmountDue):C}):");
            foreach (var c in newBills) sb.AppendLine($"{Line(c)}, due {c.DueDate:MMM d}");
            sb.AppendLine();
        }
        if (fees.Count > 0)
        {
            sb.AppendLine($"Late fees applied ({fees.Count}, total {fees.Sum(c => c.AmountDue):C}):");
            foreach (var c in fees) sb.AppendLine($"{Line(c)} for {c.BillingPeriodStart:MMMM yyyy} rent");
            sb.AppendLine();
        }
        if (statements is not null)
        {
            sb.AppendLine($"Tenant statements: {statements.Sent} sent, {statements.Skipped} skipped (no tenant email or reminders off), {statements.Failed} failed.");
            sb.AppendLine();
        }
        if (!string.IsNullOrEmpty(baseUrl)) sb.AppendLine($"Review bills: {baseUrl}/Bills");

        var subject = $"Billing run {today:MMM d}: {newBills.Count} bill(s), {fees.Count} late fee(s)";
        var sent = 0;
        foreach (var email in admins)
        {
            var log = await _mail.SendReminderAsync(baseUrl, EmailKind.BillingSummary, email,
                subject, sb.ToString(), ct: ct);
            if (log.Status == EmailStatus.Sent) sent++;
        }
        return sent;
    }
}
